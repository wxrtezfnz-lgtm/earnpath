from aiogram import Router
from aiogram.types import CallbackQuery

router = Router()


@router.callback_query()
async def menu_handler(callback: CallbackQuery):
    """
    Обработка главного меню ProfitOS
    """

    data = callback.data

    if data == "earnings":
        text = """
💰 <b>Способы заработка</b>

Доступные направления:

🔥 Фриланс
🤖 Искусственный интеллект
📱 Создание контента
💻 Онлайн-бизнес
📈 Инвестиции

Скоро здесь появятся пошаговые программы.
"""

    elif data == "ai_coach":
        text = """
🧠 <b>AI Наставник</b>

Твой персональный помощник по развитию дохода.

Он поможет:
- выбрать направление
- составить план
- найти идеи
- разобрать ошибки

Скоро подключим искусственный интеллект.
"""

    elif data == "academy":
        text = """
📚 <b>Академия ProfitOS</b>

Обучающие программы:

🎯 Старт с нуля
💼 Поиск первой работы
🚀 Создание дохода онлайн

Раздел находится в разработке.
"""

    elif data == "tools":
        text = """
📈 <b>Инструменты</b>

Полезные инструменты:

🧮 Калькуляторы
📊 Аналитика
💡 Генератор идей

Скоро будет доступно.
"""

    elif data == "roadmap":
        text = """
🎯 <b>План развития</b>

Твой путь:

1️⃣ Определение навыков
2️⃣ Выбор направления
3️⃣ Первые действия
4️⃣ Первые деньги
5️⃣ Масштабирование
"""

    elif data == "profile":
        text = """
👤 <b>Профиль</b>

Здесь будет:

📌 Статистика
⭐ Статус подписки
🏆 Достижения
📈 Прогресс
"""

    elif data == "premium":
        text = """
⭐ <b>ProfitOS Premium</b>

Полный доступ:

✅ Все способы заработка
✅ Закрытая база знаний
✅ AI Наставник
✅ Эксклюзивные материалы

Скоро подключим оплату.
"""

    else:
        text = "Раздел находится в разработке 🚧"


    await callback.message.edit_text(
        text
    )

    await callback.answer()